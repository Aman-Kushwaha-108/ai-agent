def parse_agent_decision(raw):
    """Parse and validate the model's requested action."""
    match = re.search(r"\{.*\}", raw, flags=re.DOTALL)

    if not match:
        return None

    try:
        data = json.loads(match.group(0))
    except json.JSONDecodeError:
        return None

    if not isinstance(data, dict):
        return None

    action = data.get("action")

    if action == "respond":
        response = data.get("response", "")
        if isinstance(response, str) and response.strip():
            return {"action": "respond", "response": response}
        return None

    if action != "tool":
        return None

    tool_name = data.get("tool")
    arguments = data.get("arguments", {})

    if tool_name not in TOOL_REGISTRY or not isinstance(arguments, dict):
        return None

    return {
        "action": "tool",
        "tool": tool_name,
        "arguments": arguments
    }


def deterministic_fallback(task):
    """
    Conservative fallback if the small model fails to produce
    a valid action. It does not execute arbitrary model-generated code.
    """
    text = task.lower()

    if re.search(r"\b(add|create|save)\b.*\b(task|todo)\b", text):
        match = re.search(
            r"\b(?:add|create|save)\s+(?:a\s+)?(?:task|todo)\s*[:\-]?\s*(.+)",
            task,
            flags=re.IGNORECASE
        )
        if match:
            title = match.group(1).strip().strip("\"'")
            if title:
                return {
                    "action": "tool",
                    "tool": "add_task",
                    "arguments": {"title": title[:120]}
                }

    if re.search(r"\b(list|show|view)\b.*\btasks?\b", text):
        return {
            "action": "tool",
            "tool": "list_tasks",
            "arguments": {}
        }

    if re.search(r"\b(time|clock)\b", text):
        return {
            "action": "tool",
            "tool": "current_time",
            "arguments": {}
        }

    if re.search(r"\b(calculate|compute|what is)\b", text):
        match = re.search(
            r"(?:calculate|compute|what is)\s+(.+?)[?]?$",
            task,
            flags=re.IGNORECASE
        )
        if match:
            expression = match.group(1).strip().rstrip("?")
            if re.fullmatch(r"[0-9+\-*/().%\s]+", expression):
                return {
                    "action": "tool",
                    "tool": "calculator",
                    "arguments": {"expression": expression}
                }

    return {
        "action": "respond",
        "response": (
            "I couldn't confidently select a tool for that request. "
            "Try asking me to calculate an expression, search the "
            "AI knowledge base, list tasks, add a task, or check the time."
        )
    }


def run_agent(task, max_steps=MAX_AGENT_STEPS):
    if not isinstance(task, str) or not task.strip():
        return {"ok": False, "error": "Enter a task."}

    task = task.strip()
    max_steps = max(1, min(int(max_steps), MAX_AGENT_STEPS))

    agent_state.update({
        "status": "running",
        "current_task": task,
        "steps": [],
        "last_result": None
    })

    tool_observations = []

    try:
        for step_number in range(max_steps):
            prompt = f"""
You are the decision engine of a tool-using AI agent.

User task:
{task}

Available tools:
{json.dumps({name: info["description"] for name, info in TOOL_REGISTRY.items()})}

Previous tool observations:
{json.dumps(tool_observations, ensure_ascii=False)}

Choose exactly one next action and return a JSON object only.

To call a tool:
{{"action":"tool","tool":"calculator","arguments":{{"expression":"12*4"}}}}

To respond to the user:
{{"action":"respond","response":"Your final answer"}}

Rules:
- Use only the listed tools.
- Never invent tool results.
- Use observations from previous steps.
- If enough information is available, respond.
- Do not repeat a tool call that already failed.
- Do not request more than one action at a time.
"""

            raw = generate_text(prompt, max_new_tokens=180, temperature=0)
            decision = parse_agent_decision(raw)

            if decision is None:
                decision = deterministic_fallback(task)
                agent_state["steps"].append({
                    "step": step_number + 1,
                    "type": "fallback",
                    "reason": "Invalid or unparseable model action"
                })

            if decision["action"] == "respond":
                final_response = decision["response"]

                # Add trusted observations to help prevent fabricated claims.
                if tool_observations:
                    observation_text = json.dumps(
                        tool_observations, ensure_ascii=False
                    )
                    final_prompt = f"""
Answer the user's task using the tool observations below.
Do not claim facts that are not supported by those observations.
If a tool failed, explain the limitation.

User task: {task}
Tool observations: {observation_text}
Proposed response: {final_response}

Provide a concise final answer.
"""
                    final_response = generate_text(
                        final_prompt, max_new_tokens=180, temperature=0
                    )

                agent_state["status"] = "completed"
                agent_state["last_result"] = final_response

                conversation_memory.append({
                    "task": task,
                    "response": final_response,
                    "timestamp": datetime.now(timezone.utc).isoformat()
                })

                return {
                    "ok": True,
                    "task": task,
                    "response": final_response,
                    "steps": agent_state["steps"],
                    "observations": tool_observations
                }

            tool_name = decision["tool"]
            arguments = decision["arguments"]

            # Safety: no unapproved tool names or unexpected arguments.
            result = execute_tool(tool_name, arguments)

            record = {
                "step": step_number + 1,
                "tool": tool_name,
                "arguments": arguments,
                "result": result
            }

            agent_state["steps"].append(record)
            tool_observations.append(record)

        # Do not silently continue beyond the step limit.
        final_response = (
            "I reached the maximum number of agent steps. "
            "Review the tool observations and try a narrower task."
        )

        agent_state["status"] = "step_limit_reached"
        agent_state["last_result"] = final_response

        return {
            "ok": True,
            "task": task,
            "response": final_response,
            "steps": agent_state["steps"],
            "observations": tool_observations
        }

    except Exception as error:
        agent_state["status"] = "error"
        return {
            "ok": False,
            "error": f"{type(error).__name__}: {str(error)}",
            "steps": agent_state["steps"]
        }


