def execute_tool(tool_name, arguments):
    if tool_name not in TOOL_REGISTRY:
        return {"ok": False, "error": "Tool is not allowlisted."}

    if not isinstance(arguments, dict):
        return {"ok": False, "error": "Arguments must be a JSON object."}

    allowed_arguments = {
        "calculator": {"expression"},
        "search_knowledge": {"query"},
        "list_tasks": set(),
        "add_task": {"title"},
        "current_time": set()
    }

    if set(arguments) - allowed_arguments[tool_name]:
        return {"ok": False, "error": "Unexpected tool arguments."}

    required_arguments = {
        "calculator": {"expression"},
        "search_knowledge": {"query"},
        "list_tasks": set(),
        "add_task": {"title"},
        "current_time": set()
    }

    if not required_arguments[tool_name].issubset(arguments):
        return {"ok": False, "error": "Required tool arguments are missing."}

    try:
        result = TOOL_REGISTRY[tool_name]["function"](**arguments)
        return {"ok": True, "result": result}
    except Exception as error:
        return {
            "ok": False,
            "error": f"{type(error).__name__}: {str(error)}"
        }


