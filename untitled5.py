def tool_search_knowledge(query):
    """Search the local educational knowledge base."""
    query_words = set(re.findall(r"[a-z]+", query.lower()))

    ranked = []

    for key, content in knowledge_base.items():
        searchable = (key + " " + content).lower()
        score = sum(
            word in searchable for word in query_words
            if len(word) > 2
        )

        if score:
            ranked.append((score, key, content))

    ranked.sort(reverse=True)

    return {
        "query": query,
        "results": [
            {"topic": key, "content": content}
            for _, key, content in ranked[:3]
        ]
    }


